
import '../../domain/entity/orderBookResponse_parmams.dart';

class OrderBookItemResponseModel extends OrderBookResponseParams{
  OrderBookItemResponseModel({
    required super.status,
    required super.errorCode,
    required super.message,
    required super.iv,
    required super.data,
    super.items,
  });

  factory OrderBookItemResponseModel.fromRawJson(Map<String, dynamic> json) {
    return OrderBookItemResponseModel(
        status: json['status'] as String? ?? '',
        errorCode: json['error_code'] as String? ?? '',
        message: json['message'] as String? ?? '',
        iv: json['iv'] as String? ?? '',
        data: json['data'] as String? ?? '',
);
}
  /// Parses raw fields AND attaches the decrypted, parsed watchlist items.
  factory OrderBookItemResponseModel.fromDecrypted({
    required Map<String, dynamic> rawJson,
    required List<dynamic> decryptedList,
  }) {
    return OrderBookItemResponseModel(
      status: rawJson['status'] as String? ?? '',
      errorCode: rawJson['error_code'] as String? ?? '',
      message: rawJson['message'] as String? ?? '',
      iv: rawJson['iv'] as String? ?? '',
      data: rawJson['data'] as String? ?? '',
      items: decryptedList
          .map((e) => OrderBookItemModel.fromJson(e as Map<String, dynamic>))
          .toList(),
    );
  }
}
